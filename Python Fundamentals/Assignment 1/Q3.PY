# Ask the user to enter two integers and one float.Conver to them all to float sand print their average.
num1 = int(input("Enter the number: "))
num2 = int(input("Enter the number: "))
num3 = float(input("Enter the number: "))

convert_num1 = float(num1)
convert_num2 = float(num2)

print(convert_num1)
print(convert_num2)

average = (convert_num1 + convert_num2 + num3) / 3
print(average)